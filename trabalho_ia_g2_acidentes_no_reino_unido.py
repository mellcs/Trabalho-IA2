def prever_risco(distrito, luz, via, area, superficie, clima, mes, dia):
    lat, lon = dist_xy.loc[distrito]
    m, dw = MESES.index(mes) + 1, DIAS.index(dia)
    cat = {"Light_Conditions": luz, "Road_Surface_Conditions": superficie,
           "Road_Type": via, "Urban_or_Rural_Area": area, "Weather_Conditions": clima,
           "Vehicle_Type": "Car",            # o modelo não usa o veículo; valor fixo
           "District Area": distrito}
    xc = torch.tensor([[maps[c][cat[c]] for c in CATS]], dtype=torch.long)
    num = [(lat - mu["Latitude"]) / sd["Latitude"], (lon - mu["Longitude"]) / sd["Longitude"],
           np.sin(2 * np.pi * m / 12), np.cos(2 * np.pi * m / 12),
           np.sin(2 * np.pi * dw / 7), np.cos(2 * np.pi * dw / 7), float(dw >= 5)]
    xn = torch.tensor([num], dtype=torch.float32)
