import copy, time

def treinar(ocultas=(128, 64), dropout=0.3, otimizador="adam", lr=1e-3, weight_decay=0.0,
            pos_weight=None, perda_fn=None, epocas=15, paciencia=3, semente=42):
    torch.manual_seed(semente)
    m = RedeAcidentes(VOCAB, n_num=len(NUM), ocultas=ocultas, dropout=dropout).to(device)
    if otimizador == "adam":
        opt = torch.optim.Adam(m.parameters(), lr=lr, weight_decay=weight_decay)
    else:
        opt = torch.optim.SGD(m.parameters(), lr=lr, momentum=0.9, weight_decay=weight_decay)
    pw = None if pos_weight is None else torch.tensor(float(pos_weight), device=device)
    perda = perda_fn if perda_fn is not None else nn.BCEWithLogitsLoss(pos_weight=pw)

    melhor, melhor_estado, sem_melhora, hist = -1, None, 0, []
    for ep in range(1, epocas + 1):
        t0, soma = time.time(), 0.0
        m.train()
        for xc, xn, yb in dl_tr:
            xc, xn, yb = xc.to(device), xn.to(device), yb.to(device)
            opt.zero_grad()
            l = perda(m(xc, xn), yb)
            l.backward()
            opt.step()
            soma += l.item() * len(yb)
        custo_tr = soma / len(dl_tr.dataset)
        ap = average_precision_score(yb_va, prever(m, dl_va))
        hist.append((custo_tr, ap))
        print(f"época {ep:2d} | custo treino {custo_tr:.4f} | PR-AUC val {ap:.4f} | {time.time() - t0:.0f}s")
        if ap > melhor:
            melhor, melhor_estado, sem_melhora = ap, copy.deepcopy(m.state_dict()), 0
        else:
            sem_melhora += 1
            if sem_melhora >= paciencia:
                print("early stopping")
                break
    m.load_state_dict(melhor_estado)   # volta para a melhor época
    return m, hist

