import torch, torch.nn as nn
from torch.utils.data import TensorDataset, DataLoader

device = "cuda" if torch.cuda.is_available() else "cpu"
print("device:", device)
torch.manual_seed(42)

def tensores(Xc, Xn, yb):
    return (torch.tensor(Xc, dtype=torch.long),
            torch.tensor(Xn, dtype=torch.float32),
            torch.tensor(yb, dtype=torch.float32))

dl_tr = DataLoader(TensorDataset(*tensores(Xc_tr, Xn_tr, yb_tr)), batch_size=1024, shuffle=True)
dl_va = DataLoader(TensorDataset(*tensores(Xc_va, Xn_va, yb_va)), batch_size=4096)

VOCAB = [len(maps[c]) + 1 for c in CATS]     # inclui o código 0 (categoria desconhecida)
def dim_emb(n): return min(16, (n + 1) // 2)  # regra prática para o tamanho do embedding

class RedeAcidentes(nn.Module):
    def __init__(self, vocab, n_num, ocultas=(128, 64), dropout=0.3):
        super().__init__()
        self.embs = nn.ModuleList([nn.Embedding(n, dim_emb(n)) for n in vocab])
        d_in = sum(dim_emb(n) for n in vocab) + n_num
        camadas = []
        for h in ocultas:
            camadas += [nn.Linear(d_in, h), nn.ReLU(), nn.Dropout(dropout)]
            d_in = h
        camadas.append(nn.Linear(d_in, 1))
        self.mlp = nn.Sequential(*camadas)

    def forward(self, xc, xn):
        e = [emb(xc[:, i]) for i, emb in enumerate(self.embs)]
        return self.mlp(torch.cat(e + [xn], dim=1)).squeeze(1)   # devolve o logit

@torch.no_grad()
def prever(modelo, dl):
    modelo.eval()
    out = [torch.sigmoid(modelo(xc.to(device), xn.to(device))).cpu() for xc, xn, _ in dl]
    return torch.cat(out).numpy()

